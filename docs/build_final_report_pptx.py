def add_speaker_notes(prs):
    """講稿 md 之「### 第 N 頁」各節寫入對應投影片之備忘稿欄位（去除 Markdown 粗體與程式碼標記）。"""
    import re
    if not NOTES_MD.exists():
        print("講稿檔不存在，略過備忘稿：", NOTES_MD)
        return
    secs = re.split(r"^### 第 (\d+) 頁[^\n]*\n", NOTES_MD.read_text(encoding="utf-8"), flags=re.M)
    n = 0
    for k in range(1, len(secs), 2):
        idx = int(secs[k]) - 1
        body = re.sub(r"\*\*|`", "", secs[k + 1].split("\n## ")[0]).strip()   # 文末附錄（## 標題）不寫入
        if 0 <= idx < len(prs.slides) and body:
            prs.slides[idx].notes_slide.notes_text_frame.text = body
            n += 1
    print("備忘稿寫入", n, "頁")


