def pic(s, name, x, y, w, h):
    """等比例縮放置入 (x, y, w, h) 方框內並置中。"""
    f = DOCS / name
    iw, ih = Image.open(f).size
    sc = min(w / iw, h / ih)
    pw, ph = iw * sc, ih * sc
    s.shapes.add_picture(str(f), Inches(x + (w - pw) / 2), Inches(y + (h - ph) / 2), Inches(pw), Inches(ph))


def side_box(s, x, y, w, h, title, items, size=12.5):
    box = s.shapes.add_shape(MSO_SHAPE.RECTANGLE, Inches(x), Inches(y), Inches(w), Inches(h))
    box.fill.solid(); box.fill.fore_color.rgb = GRAY_ROW2; box.line.color.rgb = GRAY_ROW
    text(s, x + 0.15, y + 0.1, w - 0.3, 0.4, title, size=16, bold=True, color=NAVY)
    bullets(s, x + 0.15, y + 0.6, w - 0.3, h - 0.7, items, size=size, after=8)


