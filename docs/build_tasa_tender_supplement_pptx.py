def qa(prs, n, title, h=0.85):
    """問答頁：標題 Qn＋問題框（灰底），回傳 (slide, 答覆區起始 y)。"""
    from pptx.enum.shapes import MSO_SHAPE
    s = frame(prs, f"Q{n}　{title}", 0)
    box = s.shapes.add_shape(MSO_SHAPE.RECTANGLE, Inches(0.62), Inches(0.95), Inches(12.1), Inches(h))
    box.fill.solid(); box.fill.fore_color.rgb = T.GRAY_ROW2; box.line.color.rgb = T.GRAY_ROW
    text(s, 0.75, 1.0, 11.85, h - 0.1, [[("問：", H), (QS[n], {})]], size=13)
    text(s, 0.62, 0.95 + h + 0.08, 1.0, 0.35, "答：", size=14, bold=True, color=NAVY)
    return s, 0.95 + h + 0.45


